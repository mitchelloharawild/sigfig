test_that("uses coarsest p and full values", {
  z <- precision(3.2, 1) + precision(4.12, 2)
  expect_equal(prec_value(z), 7.32)
  expect_identical(prec_digits(z), 1L)
  expect_identical(format(z), "7.3")

  x <- precision(c(7.25, 8), c(2, NA))
  y <- precision(c(2.5, 3), c(1, NA))
  for (op in c("+", "-", "*", "/", "^", "%%", "%/%")) {
    f <- match.fun(op)
    expect_identical(f(x, y), precision(f(c(7.25, 8), c(2.5, 3)), c(1, NA)))
    expect_identical(f(x, 2), precision(f(c(7.25, 8), 2), c(2, NA)))
    expect_identical(f(2, x), precision(f(2, c(7.25, 8)), c(2, NA)))
    expect_identical(f(2L, x), f(2, x))
    expect_identical(f(x, 1:2), precision(f(c(7.25, 8), 1:2), c(2, NA)))
    expect_identical(f(x, precision(2, 0)), precision(f(c(7.25, 8), 2), 0))
  }
  expect_identical(-x, precision(c(-7.25, -8), c(2, NA)))
  expect_identical(+x, x)
})

test_that("missing values", {
  x <- precision(1, 2)
  expect_identical(x + NA, precision(NA, 2))
  expect_identical(NA + x, precision(NA, 2))
  expect_identical(x + NA_integer_, precision(NA, 2))
  expect_identical(format(precision(NA, 0) + x), "NA")
})

test_that("sizes", {
  x <- precision(1:3, 1)
  expect_error(x + precision(), class = "vctrs_error_incompatible_size")
  expect_length(precision(1) + precision(), 0)
  expect_length(precision() + 1, 0)
  expect_error(x + 1:2, class = "vctrs_error_incompatible_size")
  expect_identical(x + c(a = 1), precision(2:4, 1))
})

test_that("unsupported", {
  x <- precision(1, 1)
  expect_error(x + "a", class = "vctrs_error_incompatible_op")
  expect_error("a" + x, class = "vctrs_error_incompatible_op")
  expect_error(x + TRUE, class = "vctrs_error_incompatible_op")
  expect_error(x & x, class = "vctrs_error_incompatible_op")
  expect_error(!x, class = "vctrs_error_incompatible_op")
  expect_error(vctrs::vec_arith("+", x, factor("a")), class = "vctrs_error_incompatible_op")
  expect_error(x + matrix(1), "dimensions")
})

test_that("summaries", {
  x <- precision(c(1.25, 2.5, 4), c(2, 1, NA))
  expect_identical(sum(x), precision(7.75, 1))
  expect_identical(sum(x, 1, precision(2, 0)), precision(10.75, 0))
  expect_identical(prod(x), precision(12.5, 1))
  expect_identical(mean(x), precision(7.75 / 3, 1))
  expect_identical(mean(x, trim = 0.4), precision(2.5, 1))
  expect_identical(min(x), precision(1.25, 1))
  expect_identical(max(x), precision(4, 1))
  expect_identical(range(x), precision(c(1.25, 4), 1))
  expect_identical(median(x), precision(2.5, 1))
  expect_identical(quantile(x, c(0, 1)), precision(c(1.25, 4), 1))
  expect_identical(sum(precision(1:2)), precision(3))
  expect_identical(sum(precision()), precision(0))
  y <- precision(c(1.25, NA), c(2, 0))
  expect_true(is.na(sum(y)))
  expect_identical(sum(y, na.rm = TRUE), precision(1.25, 2))
  expect_identical(mean(y, na.rm = TRUE), precision(1.25, 2))
  expect_identical(median(y, na.rm = TRUE), precision(1.25, 2))
  expect_identical(median(y), precision(NA, 0))
  expect_error(any(x), "not supported")
  expect_error(quantile(y), "missing")
  expect_warning(min(precision()), "Inf")
})

test_that("cumulative", {
  x <- precision(c(3, 1.25, 2.5, 4), c(NA, 2, 1, 3))
  p <- c(NA, 2, 1, 1)
  expect_identical(cumsum(x), precision(cumsum(c(3, 1.25, 2.5, 4)), p))
  expect_identical(cumprod(x), precision(cumprod(c(3, 1.25, 2.5, 4)), p))
  expect_identical(cummin(x), precision(c(3, 1.25, 1.25, 1.25), p))
  expect_identical(cummax(x), precision(c(3, 3, 3, 4), p))
})

test_that("math", {
  x <- precision(c(4, -2.75, 1234), c(1, NA, -2))
  expect_identical(abs(x), precision(c(4, 2.75, 1234), c(1, NA, -2)))
  expect_identical(sqrt(x[1]), precision(2, 1))
  expect_identical(log(x[1], 2), precision(2, 1))
  expect_identical(sign(x), precision(c(1, -1, 1)))
  expect_identical(floor(x), precision(c(4, -3, 1234), c(0, NA, -2)))
  expect_identical(ceiling(x), precision(c(4, -2, 1234), c(0, NA, -2)))
  expect_identical(trunc(x), precision(c(4, -2, 1234), c(0, NA, -2)))
  expect_identical(is.finite(x / 0), rep(FALSE, 3))
  expect_identical(is.infinite(x / 0), rep(TRUE, 3))
  expect_identical(is.nan(precision(c(NaN, NA), 1)), c(TRUE, FALSE))
})

test_that("rounding", {
  x <- precision(c(1234.567, 1.5, 1234), c(3, NA, -2))
  expect_identical(round(x), precision(c(1235, 2, 1234), c(0, 0, -2)))
  expect_identical(round(x, 1), precision(c(1234.6, 1.5, 1234), c(1, 1, -2)))
  expect_identical(round(x, c(2, 0, -3)), precision(c(1234.57, 2, 1000), c(2, 0, -3)))
  expect_identical(signif(precision(c(9.96, 0, 1234.567), 3), 2), precision(c(10, 0, 1200), c(0, 3, -2)))
  expect_error(round(x, 1:2), class = "vctrs_error_incompatible_size")
  expect_error(round(x, NA), "missing")
  expect_length(round(precision()), 0)
})
