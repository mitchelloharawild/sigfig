test_that("uses coarsest p and full values", {
  z <- sigfig(3.2, 1) + sigfig(4.12, 2)
  expect_equal(prec_value(z), 7.32)
  expect_identical(prec_digits(z), 1L)
  expect_identical(format(z), "7.3")

  x <- sigfig(c(7.25, 8), c(2, NA))
  y <- sigfig(c(2.5, 3), c(1, NA))
  for (op in c("+", "-", "*", "/", "^", "%%", "%/%")) {
    f <- match.fun(op)
    expect_identical(f(x, y), sigfig(f(c(7.25, 8), c(2.5, 3)), c(1, NA)))
    expect_identical(f(x, 2), sigfig(f(c(7.25, 8), 2), c(2, NA)))
    expect_identical(f(2, x), sigfig(f(2, c(7.25, 8)), c(2, NA)))
    expect_identical(f(2L, x), f(2, x))
    expect_identical(f(x, 1:2), sigfig(f(c(7.25, 8), 1:2), c(2, NA)))
    expect_identical(f(x, sigfig(2, 0)), sigfig(f(c(7.25, 8), 2), 0))
  }
  expect_identical(-x, sigfig(c(-7.25, -8), c(2, NA)))
  expect_identical(+x, x)
})

test_that("missing values", {
  x <- sigfig(1, 2)
  expect_identical(x + NA, sigfig(NA, 2))
  expect_identical(NA + x, sigfig(NA, 2))
  expect_identical(x + NA_integer_, sigfig(NA, 2))
  expect_identical(format(sigfig(NA, 0) + x), "NA")
})

test_that("sizes", {
  x <- sigfig(1:3, 1)
  expect_error(x + sigfig(), class = "vctrs_error_incompatible_size")
  expect_length(sigfig(1) + sigfig(), 0)
  expect_length(sigfig() + 1, 0)
  expect_error(x + 1:2, class = "vctrs_error_incompatible_size")
  expect_identical(x + c(a = 1), sigfig(2:4, 1))
})

test_that("unsupported", {
  x <- sigfig(1, 1)
  expect_error(x + "a", class = "vctrs_error_incompatible_op")
  expect_error("a" + x, class = "vctrs_error_incompatible_op")
  expect_error(x + TRUE, class = "vctrs_error_incompatible_op")
  expect_error(x & x, class = "vctrs_error_incompatible_op")
  expect_error(!x, class = "vctrs_error_incompatible_op")
  expect_error(vctrs::vec_arith("+", x, factor("a")), class = "vctrs_error_incompatible_op")
  expect_error(x + matrix(1), "dimensions")
})

test_that("summaries", {
  x <- sigfig(c(1.25, 2.5, 4), c(2, 1, NA))
  expect_identical(sum(x), sigfig(7.75, 1))
  expect_identical(sum(x, 1, sigfig(2, 0)), sigfig(10.75, 0))
  expect_identical(prod(x), sigfig(12.5, 1))
  expect_identical(mean(x), sigfig(7.75 / 3, 1))
  expect_identical(mean(x, trim = 0.4), sigfig(2.5, 1))
  expect_identical(min(x), sigfig(1.25, 1))
  expect_identical(max(x), sigfig(4, 1))
  expect_identical(range(x), sigfig(c(1.25, 4), 1))
  expect_identical(median(x), sigfig(2.5, 1))
  expect_identical(quantile(x, c(0, 1)), sigfig(c(1.25, 4), 1))
  expect_identical(sum(sigfig(1:2)), sigfig(3))
  expect_identical(sum(sigfig()), sigfig(0))
  y <- sigfig(c(1.25, NA), c(2, 0))
  expect_true(is.na(sum(y)))
  expect_identical(sum(y, na.rm = TRUE), sigfig(1.25, 2))
  expect_identical(mean(y, na.rm = TRUE), sigfig(1.25, 2))
  expect_identical(median(y, na.rm = TRUE), sigfig(1.25, 2))
  expect_identical(median(y), sigfig(NA, 0))
  expect_error(any(x), "not supported")
  expect_error(quantile(y), "missing")
  expect_warning(min(sigfig()), "Inf")
})

test_that("cumulative", {
  x <- sigfig(c(3, 1.25, 2.5, 4), c(NA, 2, 1, 3))
  p <- c(NA, 2, 1, 1)
  expect_identical(cumsum(x), sigfig(cumsum(c(3, 1.25, 2.5, 4)), p))
  expect_identical(cumprod(x), sigfig(cumprod(c(3, 1.25, 2.5, 4)), p))
  expect_identical(cummin(x), sigfig(c(3, 1.25, 1.25, 1.25), p))
  expect_identical(cummax(x), sigfig(c(3, 3, 3, 4), p))
})

test_that("math", {
  x <- sigfig(c(4, -2.75, 1234), c(1, NA, -2))
  expect_identical(abs(x), sigfig(c(4, 2.75, 1234), c(1, NA, -2)))
  expect_identical(sqrt(x[1]), sigfig(2, 1))
  expect_identical(log(x[1], 2), sigfig(2, 1))
  expect_identical(sign(x), sigfig(c(1, -1, 1)))
  expect_identical(floor(x), sigfig(c(4, -3, 1234), c(0, NA, -2)))
  expect_identical(ceiling(x), sigfig(c(4, -2, 1234), c(0, NA, -2)))
  expect_identical(trunc(x), sigfig(c(4, -2, 1234), c(0, NA, -2)))
  expect_identical(is.finite(x / 0), rep(FALSE, 3))
  expect_identical(is.infinite(x / 0), rep(TRUE, 3))
  expect_identical(is.nan(sigfig(c(NaN, NA), 1)), c(TRUE, FALSE))
})

test_that("rounding", {
  x <- sigfig(c(1234.567, 1.5, 1234), c(3, NA, -2))
  expect_identical(round(x), sigfig(c(1235, 2, 1234), c(0, 0, -2)))
  expect_identical(round(x, 1), sigfig(c(1234.6, 1.5, 1234), c(1, 1, -2)))
  expect_identical(round(x, c(2, 0, -3)), sigfig(c(1234.57, 2, 1000), c(2, 0, -3)))
  expect_identical(signif(sigfig(c(9.96, 0, 1234.567), 3), 2), sigfig(c(10, 0, 1200), c(0, 3, -2)))
  expect_error(round(x, 1:2), class = "vctrs_error_incompatible_size")
  expect_error(round(x, NA), "missing")
  expect_length(round(sigfig()), 0)
})
